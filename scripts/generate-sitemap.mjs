/**
 * Generates the hosting metadata from a single route table:
 *
 *   public/sitemap.xml   -> the public URLs, for crawlers
 *   public/robots.txt    -> crawl policy plus the sitemap location
 *   public/_redirects    -> Cloudflare Pages rewrites for the SPA routes
 *
 * Run automatically before `vite build`. Run it by hand with:
 *   node scripts/generate-sitemap.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const { url } = JSON.parse(
  readFileSync(join(root, 'src/config/site.json'), 'utf8'),
)

const base = url.replace(/\/$/, '')

/** The public routes of the site. */
const routes = [
  { path: '/', priority: '1.0', changefreq: 'weekly' },
  { path: '/projects', priority: '0.9', changefreq: 'weekly' },
  { path: '/services', priority: '0.8', changefreq: 'monthly' },
  { path: '/about', priority: '0.6', changefreq: 'monthly' },
  { path: '/contact', priority: '0.7', changefreq: 'yearly' },
]

/**
 * The most recent edit time across `src/`, used as `lastmod`. Using the real
 * modification time keeps the sitemap honest instead of stamping every build
 * with today's date.
 */
function latestSourceChange(directory) {
  let latest = 0

  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const fullPath = join(directory, entry.name)
    if (entry.isDirectory()) {
      latest = Math.max(latest, latestSourceChange(fullPath))
    } else {
      latest = Math.max(latest, statSync(fullPath).mtimeMs)
    }
  }

  return latest
}

const lastmod = new Date(latestSourceChange(join(root, 'src')))
  .toISOString()
  .slice(0, 10)

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes
  .map(
    (route) => `  <url>
    <loc>${base}${route.path === '/' ? '/' : route.path}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${route.changefreq}</changefreq>
    <priority>${route.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`

const robots = `# Arqeno — ${base}
User-agent: *
Allow: /

Sitemap: ${base}/sitemap.xml
`

/**
 * Cloudflare Pages only falls back to `404.html` (with a real 404 status)
 * when a request matches neither a static asset nor a rewrite rule. A
 * catch-all `/* /index.html 200` therefore answers every unknown URL with
 * 200 and the 404 page is never reached. So every real route is rewritten
 * explicitly, with and without a trailing slash, and everything else falls
 * through to `404.html`.
 */
const redirects = `# Cloudflare Pages routing — generated by scripts/generate-sitemap.mjs.
# Do not edit by hand: add the route to the \`routes\` table in that script.
#
# Real routes are rewritten to the SPA shell with a 200. Anything unmatched
# falls through to 404.html, which Pages serves with an actual 404 status.
${routes
  .flatMap((route) =>
    route.path === '/'
      ? [`/  /index.html  200`]
      : [`${route.path}  /index.html  200`, `${route.path}/  /index.html  200`],
  )
  .join('\n')}
`

writeFileSync(join(root, 'public/sitemap.xml'), sitemap, 'utf8')
writeFileSync(join(root, 'public/robots.txt'), robots, 'utf8')
writeFileSync(join(root, 'public/_redirects'), redirects, 'utf8')

console.log(
  `sitemap.xml, robots.txt and _redirects written for ${base} (lastmod ${lastmod})`,
)
